/**
 * Universal Language Switcher function
 * Updates all DOM elements with data-i18n, data-i18n-html, data-i18n-ph, data-i18n-title
 */
function applyLanguage(lang) {
  const current = (lang === 'en') ? 'en' : 'te';
  const dict = I18N[current];
  if (!dict) return;

  // 1. Text elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // 2. HTML elements
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // 3. Placeholders
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // 4. Titles / Tooltips
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key]) {
      el.title = dict[key];
    }
  });

  // 5. Update html lang attribute
  document.documentElement.lang = current;
}

if (typeof window !== 'undefined') {
  window.I18N = I18N;
  window.applyLanguage = applyLanguage;
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { I18N, applyLanguage };
}

